// The kana (154-253) share one placeholder shape.
const KANA = ['.#####.', '.#...#.', '.#...#.', '.#...#.', '.#####.'];

// For each code: width (pixels advanced) and rows as bitmasks, bit 0 = leftmost.
export const GLYPH_W = new Uint8Array(256);
export const GLYPH_ROWS = Array.from({ length: 256 }, () => new Uint8Array(5));

for (let c = 16; c < 128; c++) {
  const ch = String.fromCharCode(c);
  const def = NARROW[ch] ?? NARROW[ch.toLowerCase()];
  GLYPH_W[c] = 4;
  if (!def) continue;
  for (let r = 0; r < 5; r++) {
    const v = +def[r];
    GLYPH_ROWS[c][r] = ((v >> 2) & 1) | (((v >> 1) & 1) << 1) | ((v & 1) << 2);
  }
}
for (let c = 128; c < 256; c++) {
  const rows = WIDE[c] ?? KANA;
  GLYPH_W[c] = 8;
  for (let r = 0; r < 5; r++) {
    let m = 0;
    for (let x = 0; x < 7; x++) if (rows[r][x] === '#') m |= 1 << x;
    GLYPH_ROWS[c][r] = m;
  }
}
