#!/usr/bin/env node
// Writes sw.js, the service worker that lets the app run offline as an
// installed PWA. It lists the app's own files (the page, styles, manifest,
// icons, everything under src/, and any ROMs committed under roms/, such as
// a bundled demo) and stamps a hash of their contents into the cache name,
// so any change to the app makes browsers fetch a fresh copy.
//
// Run it after changing files (npm start does): node tools/build-sw.mjs

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execSync } from 'node:child_process';

const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const name = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).name;

const walk = (dir) => fs.readdirSync(path.join(root, dir), { withFileTypes: true }).flatMap((e) => {
  const rel = path.posix.join(dir, e.name);
  if (e.name.startsWith('.')) return [];
  return e.isDirectory() ? walk(rel) : [rel];
});
const top = fs.readdirSync(root).filter((f) => /^(index\.html|style\.css|manifest\.webmanifest|favicon.*|icon-.*\.png)$/.test(f));
let bundled = [];
try { bundled = execSync('git ls-files roms', { cwd: root, encoding: 'utf8' }).split('\n').filter(Boolean); } catch { /* not a git checkout */ }
const files = [...top, ...walk('src'), ...bundled].sort();

const hash = crypto.createHash('sha256');
for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(root, f))); }
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by tools/build-sw.mjs: don't edit; rerun it after changing the app.
// Offline support: the app's files are cached when the worker installs, and
// every request goes to the network first (so a connected device always gets
// the current app) and falls back to the cache when offline. ROM sets under
// roms/ aren't cached here: games kept on the device live in IndexedDB.

const CACHE = '${name}-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 2)};
const BUNDLED = new Set(${JSON.stringify(bundled)});

// Tell the app's open pages how an install is going (src/sw-update.js shows it while updating).
const tell = async (msg) => {
  for (const c of await self.clients.matchAll({ type: 'window', includeUncontrolled: true })) c.postMessage(msg);
};

// Install: fetch every file into the new cache, a few at a time, reporting progress. If any
// fails (offline partway), drop the half-filled cache: the old version keeps running.
self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE), total = FILES.length;
    let next = 0, done = 0;
    tell({ type: 'sw-progress', done, total });
    const worker = async () => {
      while (next < total) {
        await cache.add(new Request(FILES[next++], { cache: 'reload' }));
        done++;
        if (done % 4 === 0 || done === total) tell({ type: 'sw-progress', done, total });
      }
    };
    try { await Promise.all(Array.from({ length: 6 }, worker)); }
    catch (err) { await caches.delete(CACHE); throw err; }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('${name}-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim())
    .then(() => tell({ type: 'sw-active' })));
});

self.addEventListener('fetch', (event) => {
  const req = event.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  const rel = url.pathname.slice(new URL(self.registration.scope).pathname.length);
  if (rel.startsWith('roms/') && !BUNDLED.has(rel)) return;      // ROM sets: straight to the network
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    try {
      // Ask the server every time (a 304 when unchanged): the browser's own HTTP cache could otherwise
      // hand back an old module next to a new one after an update.
      const res = await (req.mode === 'navigate' ? fetch(req.url, { cache: 'no-cache', credentials: 'same-origin' }) : fetch(req, { cache: 'no-cache' }));
      if (res.ok) cache.put(req, res.clone());
      return res;
    } catch {
      const hit = await cache.match(req) || await cache.match(req, { ignoreSearch: true })
        || (req.mode === 'navigate' && (await cache.match('./') || await cache.match('index.html')));
      return hit || Response.error();
    }
  })());
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`sw.js: ${files.length + 1} files, cache ${name}-${version}`);
